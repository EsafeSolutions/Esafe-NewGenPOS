for (const [key, bars] of Object.entries(REFERENCE)) {
  const code = key.split(':').slice(1).join(':')
  check(key + ' bars', encode(code).modules, bars)
  check(key + ' format', encode(code).format, key.split(':')[0])
}
check('EAN-13 check digit', eanCheckDigit('400638133393'), '1')
check('13 digits with a wrong check digit are not EAN-13', formatOf('6281000001237'), 'CODE128')
check('12 digits that are not a UPC-A are Code 128', formatOf('123456789013'), 'CODE128')
check('Arabic text has no barcode', formatOf('صنف'), null)
check('an empty code has no barcode', formatOf(''), null)
check('nothing drawn without a barcode', svg('صنف'), '')
check('the drawing starts after the quiet zone', svg('LP-PLAIN').includes('<rect x="10"'), true)

console.log(failures ? `${failures} FAILED` : "all passed")
